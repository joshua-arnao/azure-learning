# VNET PEERING
Conectar 2 Vnets de forma privada utilizando la red de Azure
Esta conexión es directa y rápida entre redes, sin necesidad de atraesar la red pública de internet. No debe de tener un CIDR(rango de direcciones IP) supuerpuesto.
La conexión VNet Pering **no es transitiva** (debe establecerse para cada VNet que necesite comunicarse entre sí)
